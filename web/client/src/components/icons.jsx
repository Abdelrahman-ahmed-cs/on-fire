const KEYCAP = /^([0-9])️?⃣$/;

export function toIcon(icon, size = 15) {
  if (!icon) return null;
  if (typeof icon !== 'string') return icon;
  const k = KEYCAP.exec(icon);
  if (k) return <span className="step-num">{k[1]}</span>;
  const name = EMOJI[icon] ?? EMOJI[icon.replace(/️/g, '')];
  return name ? <Icon name={name} size={size} /> : null;
}
